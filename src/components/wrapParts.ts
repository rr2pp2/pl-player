// v3.11.1：設定画面の短い名前（アイコンの枠・場所・色の行）を、言葉の切れ目で折り返すための区切り。依存の無い関数だけを置く
// （scripts\skins.test.mts から Node だけで確かめるため）。
//
// 文節で切る CSS（base.css の word-break: auto-phrase）は機械の判定なので、「ウィンドウ・タスクバー」のような「・」でつないだ名前を
// 1つの言葉と見ることがある。そうなると幅に入らないとき言葉の途中で切れるので、「・」「／」の後ろは画面が <wbr> を入れて必ず切れるようにする。
// 区切っても文字は変えない（つなぐと元の文字列に戻る）。

/** 「・」「／」の後ろで分ける（区切りの文字は前の側に残す）。区切りが無ければ1つだけ */
export function wrapParts(text: string): string[] {
  return text.split(/(?<=[・／])/).filter((p) => p !== "");
}
